"""Piece test blueprints: one of every ready piece, laid out on a grid, to check in game.

Writes one blueprint per group of categories into <out>/piece-test-<group>/. Place them in a
sandbox save (Creative mode is easiest) and look for missing or broken pieces. Pieces made from a
similar piece (🧪 in ASSETS.md) are the ones to watch.

  python -I piece_test.py [--version 46] [--out .local/blueprints]
"""
import argparse, json, math, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'scripts'))
from sbp import Library, assets, estimate_cost, write_sbpcfg, short, SIZES, out_of_bounds
from build_assets import category

GROUPS = {
    'floors-ramps': ['Floors & foundations', 'Ramps, slopes & rounded edges'],
    'walls-glass-roofs': ['Walls & facades', 'Glass & windows', 'Doors & gates', 'Roofs'],
    'structure-access-decor': ['Beams, pillars & structure', 'Walkways, stairs, railings & fences',
                               'Lights, signs & decoration'],
    'factory-logistics': ['Production machines', 'Extraction', 'Power', 'Belts, lifts & sorting',
                          'Pipes & fluids', 'Hypertubes', 'Trains, vehicles & drones', 'Storage',
                          'Special & unique buildings'],
}

ap = argparse.ArgumentParser()
ap.add_argument('--version', type=int, default=46, help='library version to test (36, 42 or 46)')
ap.add_argument('--out', default='.local/blueprints')
args = ap.parse_args()

lib = Library.load(version=args.version)
table = assets()['assets']
types = [t for t in lib.types() if t in table]

for group, cats in GROUPS.items():
    picks = sorted((t for t in types if category(t) in cats), key=lambda t: (cats.index(category(t)), t))
    if not picks:
        continue
    # cell size from the piece's footprint, + 4 m gap; pieces without a known size get 12 m
    def cell(t):
        s = table[t]['size_m']
        return max(12.0, max(s.get('width', 0), s.get('depth', 0), s.get('defaultlength', 0)) + 4)
    size = next(n for n in SIZES if SIZES[n] * 8 >= math.sqrt(sum(cell(t) ** 2 for t in picks)) * 1.25
                ) if any(SIZES[n] * 8 >= math.sqrt(sum(cell(t) ** 2 for t in picks)) * 1.25 for n in SIZES) else 'extra-large'
    bp = lib.new_blueprint(size=size)
    half = SIZES[size] * 400.0
    x, y, row_h = -half + 600, -half + 600, 0.0
    for t in picks:
        c = cell(t) * 100
        if x + c > half - 200:
            x, y, row_h = -half + 600, y + row_h, 0.0
        bp.add_copy(lib.donor(t, custom=True), lib.bp, [x + c / 2 - 600, y + c / 2 - 600, 0.0])
        x += c
        row_h = max(row_h, c)
    bad = out_of_bounds(bp)
    if bad:
        print('%s: %d pieces outside %s, skipping' % (group, len(bad), size))
        continue
    bp.recipes = lib.recipes_for(picks)
    bp.cost = estimate_cost(bp)
    title = 'Piece Test - %s (v%d)' % (group, args.version)
    d = Path(args.out) / ('piece-test-%s' % group)
    d.mkdir(parents=True, exist_ok=True)
    bp.save(d / (title + '.sbp'))
    write_sbpcfg(d / (title + '.sbpcfg'),
                 'One of every ready piece in: %s.\n\nPlace it in a sandbox save and check each piece '
                 'appears and looks right. Generated by claude-satisfactory-builder.' % ', '.join(cats))
    print('%-24s %3d pieces, %s' % (group, len(picks), size))
